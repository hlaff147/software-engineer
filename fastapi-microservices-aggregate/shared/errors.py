"""RFC 7807 Problem Details implementation for standardized error handling."""

from __future__ import annotations

from typing import Any

from fastapi import FastAPI, HTTPException, Request
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

from shared.constants import ErrorTitles, ErrorTypes, MediaTypes

__all__ = ["ProblemDetails", "ProblemDetailsException", "register_problem_handlers"]


class ProblemDetails(BaseModel):
    """RFC 7807 Problem Details response model."""

    type: str = Field(
        default=ErrorTypes.ABOUT_BLANK,
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        ...,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="Parameters that failed validation (if applicable).",
    )


class ProblemDetailsException(Exception):
    """Domain or application exception that maps directly to RFC 7807 Problem Details."""

    def __init__(
        self,
        status: int,
        title: str,
        detail: str,
        type_uri: str = ErrorTypes.ABOUT_BLANK,
        invalid_params: list[dict[str, Any]] | None = None,
    ) -> None:
        super().__init__(detail)
        self.status = status
        self.title = title
        self.detail = detail
        self.type_uri = type_uri
        self.invalid_params = invalid_params


def register_problem_handlers(app: FastAPI) -> None:
    """Registers standard exception handlers converting all errors to RFC 7807 Problem Details."""

    @app.exception_handler(ProblemDetailsException)
    async def problem_details_handler(
        request: Request, exc: ProblemDetailsException
    ) -> JSONResponse:
        problem = ProblemDetails(
            type=exc.type_uri,
            title=exc.title,
            status=exc.status,
            detail=exc.detail,
            instance=request.url.path,
            invalid_params=exc.invalid_params,
        )
        return JSONResponse(
            status_code=exc.status,
            content=problem.model_dump(exclude_none=True),
            media_type=MediaTypes.APPLICATION_PROBLEM_JSON,
        )

    @app.exception_handler(HTTPException)
    async def http_exception_handler(request: Request, exc: HTTPException) -> JSONResponse:
        titles: dict[int, str] = {
            400: "Bad Request",
            401: "Unauthorized",
            403: "Forbidden",
            404: "Not Found",
            409: "Conflict",
            422: "Unprocessable Entity",
            500: "Internal Server Error",
            502: "Bad Gateway",
            503: "Service Unavailable",
            504: "Gateway Timeout",
        }
        detail_msg = exc.detail if isinstance(exc.detail, str) else str(exc.detail)
        problem = ProblemDetails(
            type=f"{ErrorTypes.HTTP_STATUS_BASE}/{exc.status_code}",
            title=titles.get(exc.status_code, ErrorTitles.HTTP_ERROR),
            status=exc.status_code,
            detail=detail_msg,
            instance=request.url.path,
        )
        return JSONResponse(
            status_code=exc.status_code,
            content=problem.model_dump(exclude_none=True),
            headers=exc.headers,
            media_type=MediaTypes.APPLICATION_PROBLEM_JSON,
        )

    @app.exception_handler(RequestValidationError)
    async def validation_exception_handler(
        request: Request, exc: RequestValidationError
    ) -> JSONResponse:
        invalid_params = [
            {
                "name": ".".join(str(loc) for loc in err.get("loc", [])),
                "reason": err.get("msg", "Invalid value"),
                "type": err.get("type", "value_error"),
            }
            for err in exc.errors()
        ]
        problem = ProblemDetails(
            type=ErrorTypes.VALIDATION_ERROR,
            title=ErrorTitles.VALIDATION_ERROR,
            status=422,
            detail="The request body or parameters failed validation.",
            instance=request.url.path,
            invalid_params=invalid_params,
        )
        return JSONResponse(
            status_code=422,
            content=problem.model_dump(exclude_none=True),
            media_type=MediaTypes.APPLICATION_PROBLEM_JSON,
        )
